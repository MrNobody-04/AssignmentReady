import pytest
from pathlib import Path
import docx
from src.modules.jobs.job_schema import (
    FormattingSettings,
    CoverPageData,
    MarkingSchemeData,
    MarkingCriterion,
    PageNumberingSettings,
    TableOfContentsSettings,
)
from src.modules.documents.inspector import inspect_docx
from src.modules.documents.formatter import apply_formatting
from src.modules.documents.compliance import audit_compliance

def create_sample_docx(path: Path) -> Path:
    doc = docx.Document()
    doc.add_heading("1. Introduction", level=1)
    doc.add_paragraph("This is an unformatted assignment draft generated by an AI tool. It lacks standard typography and consistent line spacing.")
    
    doc.add_heading("2. Literature Review", level=1)
    doc.add_paragraph("Previous research in automated document formatting has focused on template injection and rule validation.")
    
    doc.add_heading("2.1 Existing Academic Standards", level=2)
    doc.add_paragraph("Institutions specify rigid criteria for font families (such as Times New Roman or Arial) and 1.5 line spacing.")
    
    doc.add_heading("3. Methodology & System Design", level=1)
    doc.add_paragraph("The proposed architecture processes OpenXML trees without destroying inline equations or figures.")
    
    # Add a sample table
    tbl = doc.add_table(rows=2, cols=2)
    tbl.rows[0].cells[0].text = "Parameter"
    tbl.rows[0].cells[1].text = "Value"
    tbl.rows[1].cells[0].text = "Precision"
    tbl.rows[1].cells[1].text = "99.4%"
    
    doc.add_heading("4. Conclusion", level=1)
    doc.add_paragraph("In conclusion, the system provides automated formatting for university assignments.")
    
    doc.add_heading("5. References", level=1)
    doc.add_paragraph("Smith, J. (2024). Academic Document Processing Standards. Journal of Computing, 12(3), 45-60.")
    
    doc.save(str(path))
    return path

def test_inspection(tmp_path):
    sample_file = tmp_path / "sample.docx"
    create_sample_docx(sample_file)
    
    res = inspect_docx(sample_file)
    assert res.total_words > 50
    assert len(res.detected_headings) >= 5
    assert res.has_references_section is True
    assert res.total_tables == 1

def test_full_formatting_pipeline(tmp_path):
    sample_file = tmp_path / "sample.docx"
    output_file = tmp_path / "formatted.docx"
    create_sample_docx(sample_file)
    
    settings = FormattingSettings(
        cover_page=CoverPageData(
            enabled=True,
            student_name="Alex Mercer",
            student_id="STU-99201",
            institution="University of Cambridge",
            course="MSc Advanced Computer Science",
            module_code="CS-702",
            assignment_title="Evaluation of Rule-Based OpenXML Formatting",
            submission_date="October 2026",
        ),
        marking_scheme=MarkingSchemeData(
            enabled=True,
            criteria=[
                MarkingCriterion(name="Analysis", description="Thorough analysis", max_marks=50.0, weight_percentage=50.0),
                MarkingCriterion(name="Synthesis", description="Original synthesis", max_marks=50.0, weight_percentage=50.0),
            ]
        ),
        table_of_contents=TableOfContentsSettings(enabled=True),
        page_numbering=PageNumberingSettings(enabled=True),
    )
    
    apply_formatting(sample_file, output_file, settings)
    assert output_file.exists()
    
    # Audit compliance
    report = audit_compliance(output_file, settings)
    assert report.score_percentage >= 80
    assert report.passed_count > 0
    assert any(c.id == "cover-page-check" and c.status == "PASS" for c in report.checks)
